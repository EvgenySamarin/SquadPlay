/**
 * Design theme should be used via `MaterialTheme.<designToken>` like:
 * - `MaterialTheme.colorScheme.primary`
 * - `MaterialTheme.shapes.medium`
 * - `MaterialTheme.typography.bodyMedium`
 * - etc.
 *
 * Please check this [code lab](https://developer.android.com/codelabs/jetpack-compose-theming#0) to learn how to properly use theming in compose code
 *
 * @param darkTheme Whether the current parameters will result in a dark theme.
 * @param dynamicColor Whether the theme should use a dynamic color is available on Android 12+
 * @param content The content of the application.
 */
@Composable
fun DesignSystemTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> darkScheme
        else -> lightScheme
    }

    val extendedColors = if (darkTheme) DarkExtendedColors else LightExtendedColors

    // Providing CustomColors via CompositionLocalProvider to make customColors available to all child Composable
    CompositionLocalProvider(
        LocalExtendedColors provides extendedColors,
        LocalExtendedTypography provides ExtendedTypographyImpl,
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = Shapes,
            content = content
        )
    }
}

object DesignSystemTheme {
    val extendedColors: ExtendedColors
        @Composable
        @ReadOnlyComposable
        get() = LocalExtendedColors.current
    val colorScheme: ColorScheme
        @Composable
        @ReadOnlyComposable
        get() = MaterialTheme.colorScheme
    val extendedTypography: ExtendedTypography
        @Composable
        @ReadOnlyComposable
        get() = LocalExtendedTypography.current

    val typography: androidx.compose.material3.Typography
        @Composable
        @ReadOnlyComposable
        get() = MaterialTheme.typography

    val shapes: Shapes
        @Composable
        @ReadOnlyComposable
        get() = MaterialTheme.shapes
}